-- ============================================================
-- TRIGGERS: ticket_id generation, updated_at, status log
-- ============================================================

CREATE SEQUENCE IF NOT EXISTS ticket_seq START 1;

CREATE OR REPLACE FUNCTION generate_ticket_id()
RETURNS text AS $$
DECLARE
  date_part text;
  seq_val integer;
  ticket text;
BEGIN
  date_part := to_char(now(), 'YYYYMMDD');
  SELECT nextval('ticket_seq') INTO seq_val;
  ticket := 'CL-' || date_part || '-' || lpad(seq_val::text, 4, '0');
  RETURN ticket;
END;
$$ LANGUAGE plpgsql VOLATILE;

CREATE OR REPLACE FUNCTION set_ticket_id()
RETURNS trigger AS $$
BEGIN
  IF NEW.ticket_id IS NULL OR NEW.ticket_id = '' THEN
    NEW.ticket_id := generate_ticket_id();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_set_ticket_id ON reports;
CREATE TRIGGER trg_set_ticket_id
  BEFORE INSERT ON reports
  FOR EACH ROW EXECUTE FUNCTION set_ticket_id();

CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_update_updated_at ON reports;
CREATE TRIGGER trg_update_updated_at
  BEFORE UPDATE ON reports
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();

CREATE OR REPLACE FUNCTION log_status_change()
RETURNS trigger AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO status_logs (report_id, from_status, to_status, changed_by, note)
    VALUES (NEW.id, OLD.status, NEW.status, auth.uid(), NEW.rejected_reason);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_log_status_change ON reports;
CREATE TRIGGER trg_log_status_change
  AFTER UPDATE OF status ON reports
  FOR EACH ROW EXECUTE FUNCTION log_status_change();

