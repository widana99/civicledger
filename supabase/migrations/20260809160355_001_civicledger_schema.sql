-- ============================================================
-- TABLES
-- ============================================================

CREATE TABLE IF NOT EXISTS wilayah (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  code text UNIQUE NOT NULL,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  email text UNIQUE NOT NULL,
  full_name text NOT NULL,
  phone text,
  role user_role NOT NULL DEFAULT 'masyarakat',
  wilayah_id uuid REFERENCES wilayah(id) ON DELETE SET NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id text UNIQUE NOT NULL,
  title text NOT NULL CHECK (char_length(title) >= 5),
  description text NOT NULL CHECK (char_length(description) >= 10),
  category report_category NOT NULL DEFAULT 'lainnya',
  status report_status NOT NULL DEFAULT 'pending',
  priority report_priority NOT NULL DEFAULT 'medium',
  address text NOT NULL,
  latitude double precision,
  longitude double precision,
  photo_url text,
  reporter_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  wilayah_id uuid REFERENCES wilayah(id) ON DELETE SET NULL,
  assigned_petugas_id uuid REFERENCES profiles(id) ON DELETE SET NULL,
  assigned_at timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  rejected_reason text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS status_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  from_status report_status,
  to_status report_status NOT NULL,
  changed_by uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  note text,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS completion_proofs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  photo_url text NOT NULL,
  note text,
  uploaded_by uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS upvotes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at timestamptz DEFAULT now(),
  UNIQUE (report_id, user_id)
);

CREATE TABLE IF NOT EXISTS comments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  content text NOT NULL CHECK (char_length(content) >= 1),
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ratings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  score integer NOT NULL CHECK (score >= 1 AND score <= 5),
  note text,
  created_at timestamptz DEFAULT now(),
  UNIQUE (report_id, user_id)
);

CREATE TABLE IF NOT EXISTS petugas_spesialisasi (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  petugas_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  category report_category NOT NULL,
  created_at timestamptz DEFAULT now(),
  UNIQUE (petugas_id, category)
);

