DO $$ BEGIN
  CREATE TYPE report_priority AS ENUM ('low','medium','high','urgent');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE report_category AS ENUM ('infrastruktur','lingkungan','kebersihan','pelayanan','keamanan','lainnya');
