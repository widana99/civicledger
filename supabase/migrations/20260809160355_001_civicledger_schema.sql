/*
# CivicLedger — Initial Schema for Sistem Pelaporan Masyarakat

Sistem pelaporan & penindakan aspirasi masyarakat berbasis real-time.
Platform memungkinkan warga melaporkan masalah (infrastruktur, kebersihan,
lingkungan, dll), admin memverifikasi & menugaskan petugas, petugas
menyelesaikan laporan dengan bukti foto, dan warga memberi rating.

## 1. New Tables

### `profiles`
- `id` (uuid, PK, references auth.users)
- `email` (text, unique, not null)
- `full_name` (text, not null)
- `phone` (text, nullable)
- `role` (enum: masyarakat, admin, petugas; default masyarakat)
- `wilayah_id` (uuid, FK to wilayah, nullable) — area penugasan untuk petugas
- `is_active` (boolean, default true)
- `created_at` (timestamptz)

### `wilayah` (area/district)
- `id` (uuid, PK)
- `name` (text, not null)
- `code` (text, unique, not null)
- `created_at` (timestamptz)

### `reports` (laporan masyarakat)
- `id` (uuid, PK)
- `ticket_id` (text, unique, not null) — format: CL-YYYYMMDD-XXXX
- `title` (text, not null)
- `description` (text, not null)
- `category` (enum: infrastruktur, lingkungan, kebersihan, pelayanan, keamanan, lainnya)
- `status` (enum: pending, verified, assigned, in_progress, completed, rejected; default pending)
- `priority` (enum: low, medium, high, urgent; default medium)
- `address` (text, not null)
- `latitude` (double precision, nullable)
- `longitude` (double precision, nullable)
- `photo_url` (text, nullable) — foto laporan awal (Supabase Storage)
- `reporter_id` (uuid, FK to profiles, not null)
- `wilayah_id` (uuid, FK to wilayah, nullable)
- `assigned_petugas_id` (uuid, FK to profiles, nullable)
- `assigned_at`, `started_at`, `completed_at` (timestamptz, nullable)
- `rejected_reason` (text, nullable)
- `created_at`, `updated_at` (timestamptz)

### `status_logs` (audit trail perubahan status)
- `id` (uuid, PK)
- `report_id` (uuid, FK to reports, not null)
- `from_status` (enum, nullable)
- `to_status` (enum, not null)
- `changed_by` (uuid, FK to profiles, not null)
- `note` (text, nullable)
- `created_at` (timestamptz)

### `completion_proofs` (bukti foto penyelesaian)
- `id` (uuid, PK)
- `report_id` (uuid, FK to reports, not null)
- `photo_url` (text, not null)
- `note` (text, nullable)
- `uploaded_by` (uuid, FK to profiles, not null)
- `created_at` (timestamptz)

### `upvotes` (dukungan warga pada laporan)
- `id` (uuid, PK)
- `report_id` (uuid, FK to reports, not null)
- `user_id` (uuid, FK to profiles, not null)
- `created_at` (timestamptz)
- UNIQUE (report_id, user_id)

### `comments` (komentar warga pada laporan)
- `id` (uuid, PK)
- `report_id` (uuid, FK to reports, not null)
- `user_id` (uuid, FK to profiles, not null)
- `content` (text, not null)
- `created_at` (timestamptz)

### `ratings` (rating penyelesaian oleh pelapor)
- `id` (uuid, PK)
- `report_id` (uuid, FK to reports, not null)
- `user_id` (uuid, FK to profiles, not null)
- `score` (int 1–5, not null)
- `note` (text, nullable)
- `created_at` (timestamptz)
- UNIQUE (report_id, user_id)

### `petugas_spesialisasi` (kategori yang dikuasai petugas)
- `id` (uuid, PK)
- `petugas_id` (uuid, FK to profiles, not null)
- `category` (enum, not null)
- `created_at` (timestamptz)
- UNIQUE (petugas_id, category)

## 2. Enums
- `user_role`: masyarakat, admin, petugas
- `report_status`: pending, verified, assigned, in_progress, completed, rejected
- `report_priority`: low, medium, high, urgent
- `report_category`: infrastruktur, lingkungan, kebersihan, pelayanan, keamanan, lainnya

## 3. Security (RLS)
- `profiles`: authenticated users can read all profiles (needed for names), update own.
- `wilayah`: anon + authenticated can read (public area list); only admin can insert/update.
- `reports`: authenticated can read all; reporter can insert own; reporter can update own (only while pending); admin & assigned petugas can update.
- `status_logs`: authenticated can read; only the actor (changed_by) can insert (via client), admin can insert.
- `completion_proofs`: authenticated can read; assigned petugas can insert.
- `upvotes`: authenticated can read; users can insert/delete own upvote.
- `comments`: authenticated can read; users can insert/delete own comments.
- `ratings`: authenticated can read; users can insert own rating (one per report).
- `petugas_spesialisasi`: authenticated can read; only admin can insert/delete.

## 4. Notes
- `profiles.id` defaults to `auth.uid()` so insert on signup works.
- `reports.ticket_id` auto-generated by a trigger on insert (format CL-YYYYMMDD-XXXX).
- `reports.updated_at` auto-updated via trigger.
- Status log auto-inserted via trigger on reports.status change.
- Seed data for wilayah included (contoh wilayah Indonesia).
*/

